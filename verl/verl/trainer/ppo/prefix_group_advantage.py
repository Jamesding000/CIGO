"""The prefix-group advantage estimator of prefix replay (``algorithm.adv_estimator=prefix_group``)."""

from collections import defaultdict
from typing import Any, Optional

import numpy as np
import torch

from verl.trainer.config import AlgoConfig, PrefixReplayConfig
from verl.trainer.ppo.core_algos import register_adv_est
from verl.trainer.ppo.violations import violation_penalty, violation_rules
from verl.utils.config import omega_conf_to_dataclass


def prefix_replay_config(config) -> PrefixReplayConfig:
    """``algorithm.prefix_replay`` as a PrefixReplayConfig (from a DictConfig, an AlgoConfig or a dict);
    an undeclared key raises."""
    section = None if config is None else config.get("prefix_replay")
    if isinstance(section, PrefixReplayConfig):
        return section
    return omega_conf_to_dataclass(section or {}, PrefixReplayConfig)


def _raw_reward_column(scores, violated, penalty: float) -> torch.Tensor:
    """Raw reward r_i = -penalty if row i broke a rule, else its task reward (on a tool row, the reward of
    the answer that follows the call in the same sequence)."""
    raw_reward = torch.zeros(len(violated), dtype=torch.float32)
    for i in range(len(violated)):
        raw_reward[i] = -penalty if violated[i] else float(scores[i])
    return raw_reward


def _centered_ur(turn_ur, id2idx: dict, violated, clip_percentile: float) -> tuple[torch.Tensor, dict]:
    """Centred intrinsic reward c_i = clip_q(u_i - mean_g u), with u = turn_ur, the mean taken over the
    measured, non-violating rows of group g, and clip_q winsorizing the pooled c at quantiles q and 1 - q
    (q = clip_percentile; 0 disables). Returns (c, {group: rows covered}); every other row stays at 0.
    """
    ur_col = torch.zeros(len(violated), dtype=torch.float32)
    for i in range(len(violated)):
        if turn_ur[i] is not None:
            ur_col[i] = float(turn_ur[i])
    ur_centered = torch.zeros(len(violated), dtype=torch.float32)
    ur_rows: dict[Any, list[int]] = {}
    for gid, idxs in id2idx.items():
        if len(idxs) < 2:
            continue
        meas = [i for i in idxs if turn_ur[i] is not None and not violated[i]]
        if len(meas) < 2:
            continue
        sub = ur_col[meas]
        ur_centered[meas] = sub - sub.mean()
        ur_rows[gid] = meas
    measured_all = [i for g in ur_rows.values() for i in g]
    if 0.0 < clip_percentile < 0.5 and len(measured_all) >= 20:
        mt = torch.tensor(measured_all, dtype=torch.long)
        vals = ur_centered[mt]
        lo = torch.quantile(vals, clip_percentile)
        hi = torch.quantile(vals, 1.0 - clip_percentile)
        # clipped after centering, so a clipped group's values need not sum to zero
        ur_centered[mt] = vals.clamp(min=lo, max=hi)
    return ur_centered, ur_rows


@register_adv_est("prefix_group")
def compute_prefix_group_advantage(
    token_level_rewards: torch.Tensor,
    response_mask: torch.Tensor,
    index: np.ndarray,
    epsilon: float = 1e-6,
    norm_adv_by_std_in_grpo: bool = True,
    config: Optional[AlgoConfig] = None,
    non_tensor_batch: Optional[dict] = None,
) -> tuple[torch.Tensor, torch.Tensor]:
    """Advantage of a prefix-replay row i in group g (continuations of one prefix, ``index`` = uid):

        A_i = (r_i - mean_g r) / max(std_g r, std_floor) + beta_ur * c_i / max(std_g c, ur_std_floor)

    the normalized reward plus beta_ur times the normalized intrinsic reward, with r the raw reward
    (``_raw_reward_column``) and c the centred intrinsic reward (``_centered_ur``). Without
    ``norm_adv_by_std_in_grpo`` neither term is divided. A group of fewer than 2 rows gets A = 0.
    """
    assert non_tensor_batch is not None and "prefix_action_type" in non_tensor_batch, (
        "prefix_group estimator requires prefix_action_type in non_tensor_batch "
        "(rows must be generated by prefix_replay_agent)"
    )
    replay_cfg = prefix_replay_config(config)
    beta_ur = float(replay_cfg.beta_ur)
    norm_by_std = bool(norm_adv_by_std_in_grpo)
    std_floor = float(replay_cfg.std_floor)
    ur_std_floor = float(replay_cfg.ur_std_floor)

    scores = token_level_rewards.sum(dim=-1)
    turn_ur = non_tensor_batch.get("turn_ur")
    penalty = violation_penalty(config)
    rules = violation_rules(non_tensor_batch)
    non_tensor_batch["violation"] = rules

    if beta_ur > 0.0 and turn_ur is None:
        raise ValueError(
            "algorithm.prefix_replay.beta_ur > 0 but non_tensor_batch has no 'turn_ur' column — "
            "the UR probe did not run. Set beta_ur=0 or check the probe (prefix_replay.before_advantage)."
        )

    with torch.no_grad():
        bsz = scores.shape[0]
        violated = [rule is not None for rule in rules]
        raw_reward = _raw_reward_column(scores, violated, penalty)

        def _normalize(grp: torch.Tensor, floor: float) -> torch.Tensor:
            centered = grp - grp.mean()
            if norm_by_std:
                centered = centered / max(float(grp.std()), floor)
            return centered

        id2idx = defaultdict(list)
        for i in range(bsz):
            id2idx[index[i]].append(i)

        ur_centered = torch.zeros(bsz, dtype=torch.float32)
        ur_rows: dict[Any, list[int]] = {}
        if beta_ur > 0.0 and turn_ur is not None:
            ur_centered, ur_rows = _centered_ur(turn_ur, id2idx, violated, float(replay_cfg.ur_outlier_clip_percentile))

        adv = torch.zeros_like(raw_reward)
        norm_reward_col = torch.zeros_like(raw_reward)
        adv_ur_col = torch.zeros_like(raw_reward)
        for gid, idxs in id2idx.items():
            if len(idxs) < 2:
                continue  # degenerate group: no baseline, no gradient
            row = _normalize(raw_reward[idxs], std_floor)
            for j, i in enumerate(idxs):
                norm_reward_col[i] = row[j]
            meas = ur_rows.get(gid)
            if meas:
                c = ur_centered[meas]
                z = c / max(float(c.std()), ur_std_floor) if norm_by_std else c
                pos = {i: j for j, i in enumerate(idxs)}
                for k, i in enumerate(meas):
                    row[pos[i]] = row[pos[i]] + beta_ur * z[k]
                    adv_ur_col[i] = beta_ur * z[k]
            for j, i in enumerate(idxs):
                adv[i] = row[j]

        selected = torch.zeros(bsz, dtype=torch.float32)
        for gid, idxs in id2idx.items():
            if len(idxs) >= 2:
                for i in idxs:
                    selected[i] = 1.0
        # dump columns: pr_payoff = raw reward, pr_adv_payoff = normalized reward, pr_adv = advantage
        for name, col in (
            ("pr_payoff", raw_reward),
            ("pr_adv_payoff", norm_reward_col),
            ("pr_adv_ur", adv_ur_col),
            ("pr_adv", adv),
            ("pr_selected", selected),
        ):
            non_tensor_batch[name] = np.asarray(col.detach().cpu().numpy(), dtype=np.float32)

        adv = adv.to(scores.dtype).to(scores.device)
        adv = adv.unsqueeze(-1) * response_mask

    return adv, adv
